-- Ejecutar en Query Tool conectado a la base de datos: gestion_transporte
-- Las cinco entidades satisfacen el diseño de información del caso práctico.
BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL CHECK (length(trim(nombre)) >= 3),
  correo VARCHAR(160) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol VARCHAR(12) NOT NULL DEFAULT 'operador' CHECK (rol IN ('admin','operador')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS vehiculos (
  id_vehiculo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR(12) NOT NULL UNIQUE,
  marca VARCHAR(60) NOT NULL,
  modelo VARCHAR(60) NOT NULL,
  capacidad INTEGER NOT NULL CHECK (capacidad > 0 AND capacidad <= 120),
  estado VARCHAR(12) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS conductores (
  id_conductor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres VARCHAR(120) NOT NULL,
  licencia VARCHAR(30) NOT NULL UNIQUE,
  telefono VARCHAR(20) NOT NULL,
  estado VARCHAR(12) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS rutas (
  id_ruta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origen VARCHAR(100) NOT NULL,
  destino VARCHAR(100) NOT NULL,
  distancia_km NUMERIC(9,2) NOT NULL CHECK (distancia_km > 0),
  estado VARCHAR(12) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT rutas_diferentes CHECK (lower(trim(origen)) <> lower(trim(destino))),
  CONSTRAINT ruta_unica UNIQUE (origen, destino)
);

CREATE TABLE IF NOT EXISTS viajes (
  id_viaje INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_vehiculo INTEGER NOT NULL REFERENCES vehiculos(id_vehiculo) ON DELETE RESTRICT,
  id_conductor INTEGER NOT NULL REFERENCES conductores(id_conductor) ON DELETE RESTRICT,
  id_ruta INTEGER NOT NULL REFERENCES rutas(id_ruta) ON DELETE RESTRICT,
  id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  fecha_salida TIMESTAMPTZ NOT NULL,
  fecha_llegada_prevista TIMESTAMPTZ NOT NULL,
  estado VARCHAR(15) NOT NULL DEFAULT 'programado'
      CHECK (estado IN ('programado','en_curso','finalizado','cancelado')),
  observaciones VARCHAR(250) NOT NULL DEFAULT '',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fechas_viaje_validas CHECK (fecha_llegada_prevista > fecha_salida)
);

CREATE INDEX IF NOT EXISTS idx_viajes_vehiculo_horas ON viajes (id_vehiculo, fecha_salida);
CREATE INDEX IF NOT EXISTS idx_viajes_conductor_horas ON viajes (id_conductor, fecha_salida);
CREATE INDEX IF NOT EXISTS idx_viajes_estado ON viajes (estado);
CREATE INDEX IF NOT EXISTS idx_viajes_ruta ON viajes (id_ruta);

COMMIT;
