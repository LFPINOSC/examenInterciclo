-- ============================================================
-- TABLA USUARIOS
-- Gestiona autenticacion, roles y estado del usuario.
-- ============================================================

CREATE TABLE IF NOT EXISTS usuarios (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(255) NOT NULL,

    correo VARCHAR(255) NOT NULL UNIQUE,

    password VARCHAR(255) NOT NULL,

    rol VARCHAR(30) NOT NULL
        CHECK (rol IN ('ADMIN', 'ESTUDIANTE')),

    activo BOOLEAN NOT NULL DEFAULT TRUE
);


-- ============================================================
-- TABLA CARRERAS
-- Almacena las carreras disponibles en la universidad.
-- ============================================================

CREATE TABLE IF NOT EXISTS carreras (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(120) NOT NULL UNIQUE,

    descripcion VARCHAR(255),

    activa BOOLEAN NOT NULL DEFAULT TRUE
);


-- ============================================================
-- TABLA ESTUDIANTES
-- Cada estudiante pertenece a una carrera y esta relacionado
-- con una cuenta de usuario.
-- ============================================================

CREATE TABLE IF NOT EXISTS estudiantes (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cedula VARCHAR(10) NOT NULL UNIQUE,

    nombres VARCHAR(80) NOT NULL,

    apellidos VARCHAR(80) NOT NULL,

    telefono VARCHAR(20),

    carrera_id BIGINT NOT NULL,

    usuario_id BIGINT NOT NULL UNIQUE,

    CONSTRAINT fk_estudiante_carrera
        FOREIGN KEY (carrera_id)
        REFERENCES carreras(id),

    CONSTRAINT fk_estudiante_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
);


-- ============================================================
-- TABLA ASIGNATURAS
-- Cada asignatura pertenece a una carrera.
-- ============================================================

CREATE TABLE IF NOT EXISTS asignaturas (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo VARCHAR(20) NOT NULL UNIQUE,

    nombre VARCHAR(120) NOT NULL,

    creditos INTEGER NOT NULL,

    nivel INTEGER NOT NULL,

    activa BOOLEAN NOT NULL DEFAULT TRUE,

    carrera_id BIGINT NOT NULL,

    CONSTRAINT fk_asignatura_carrera
        FOREIGN KEY (carrera_id)
        REFERENCES carreras(id)
);


-- ============================================================
-- TABLA MATRICULAS
-- Registra la matricula realizada por un estudiante.
-- ============================================================

CREATE TABLE IF NOT EXISTS matriculas (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fecha DATE NOT NULL,

    periodo VARCHAR(30) NOT NULL,

    estado VARCHAR(30) NOT NULL
        CHECK (estado IN ('ACTIVA', 'CANCELADA')),

    estudiante_id BIGINT NOT NULL,

    CONSTRAINT fk_matricula_estudiante
        FOREIGN KEY (estudiante_id)
        REFERENCES estudiantes(id)
);


-- ============================================================
-- TABLA DETALLE_MATRICULA
-- Relaciona una matricula con las asignaturas seleccionadas.
-- ============================================================

CREATE TABLE IF NOT EXISTS detalle_matricula (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    matricula_id BIGINT NOT NULL,

    asignatura_id BIGINT NOT NULL,

    CONSTRAINT fk_detalle_matricula
        FOREIGN KEY (matricula_id)
        REFERENCES matriculas(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_detalle_asignatura
        FOREIGN KEY (asignatura_id)
        REFERENCES asignaturas(id),

    CONSTRAINT uk_matricula_asignatura
        UNIQUE (matricula_id, asignatura_id)
);