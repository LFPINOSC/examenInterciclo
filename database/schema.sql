-- Control de ordenes de trabajo - esquema PostgreSQL
-- Uso opcional (Hibernate tambien crea estas tablas al arrancar la API con ddl-auto=update):
--   createdb -h localhost -U kotaro ordenes_trabajo
--   psql -h localhost -U kotaro -d ordenes_trabajo -f database/schema.sql

-- Quien opera el sistema: administrador o tecnico
CREATE TABLE IF NOT EXISTS usuarios (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(30)  NOT NULL UNIQUE,
    correo            VARCHAR(120) NOT NULL UNIQUE,
    nombre            VARCHAR(100) NOT NULL,
    password          VARCHAR(100) NOT NULL,              -- hash BCrypt, nunca texto plano
    rol               VARCHAR(10)  NOT NULL CHECK (rol IN ('ADMIN', 'TECNICO')),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    ultimo_acceso     TIMESTAMP,
    fecha_registro    TIMESTAMP    NOT NULL DEFAULT NOW()
);

-- Personas que solicitan los trabajos
CREATE TABLE IF NOT EXISTS clientes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(120) NOT NULL,
    cedula    VARCHAR(10)  NOT NULL UNIQUE,
    telefono  VARCHAR(10),
    correo    VARCHAR(120),
    direccion VARCHAR(200)
);

-- Bienes del cliente sobre los que se trabaja (1 cliente : N equipos)
CREATE TABLE IF NOT EXISTS equipos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT      NOT NULL REFERENCES clientes (id),
    tipo       VARCHAR(60) NOT NULL,
    marca      VARCHAR(60),
    modelo     VARCHAR(60),
    serie      VARCHAR(60) UNIQUE
);

-- Orden de trabajo: une cliente, equipo y tecnico asignado
CREATE TABLE IF NOT EXISTS ordenes_trabajo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(20)  NOT NULL UNIQUE,            -- OT-00001
    cliente_id    BIGINT       NOT NULL REFERENCES clientes (id),
    equipo_id     BIGINT       NOT NULL REFERENCES equipos (id),
    tecnico_id    BIGINT       REFERENCES usuarios (id),   -- NULL = sin asignar
    creado_por    BIGINT       NOT NULL REFERENCES usuarios (id),
    descripcion   VARCHAR(500) NOT NULL,
    prioridad     VARCHAR(10)  NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    estado        VARCHAR(12)  NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA')),
    fecha_ingreso DATE         NOT NULL,
    fecha_entrega DATE,
    CHECK (fecha_entrega IS NULL OR fecha_entrega >= fecha_ingreso)
);

-- Trabajo realizado dentro de una orden (1 orden : N tareas); se borran junto con la orden
CREATE TABLE IF NOT EXISTS tareas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id    BIGINT        NOT NULL REFERENCES ordenes_trabajo (id) ON DELETE CASCADE,
    descripcion VARCHAR(200)  NOT NULL,
    horas       NUMERIC(8, 2) NOT NULL DEFAULT 0 CHECK (horas >= 0),
    costo       NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (costo >= 0),
    completada  BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_equipos_cliente ON equipos (cliente_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_estado  ON ordenes_trabajo (estado);
CREATE INDEX IF NOT EXISTS idx_ordenes_tecnico ON ordenes_trabajo (tecnico_id);
CREATE INDEX IF NOT EXISTS idx_tareas_orden    ON tareas (orden_id);
